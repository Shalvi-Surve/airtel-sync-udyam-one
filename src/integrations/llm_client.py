"""Optional LLM boundary. No provider is configured in the demo."""
import os

def is_configured() -> bool:
    return bool(os.getenv("UDYAMONE_LLM_API_KEY"))

def explain_recommendations(profile, recommendations):
    """Fail clearly rather than returning fabricated provider output."""
    if not is_configured():
        return "AI provider is not configured. Recommendations are generated by deterministic catalogue and eligibility rules."
    raise NotImplementedError("Configure a vetted provider adapter before enabling LLM calls.")
